def area(a):
    '''
    Возвращает площадь квадрата.

    Параметры:
        a (int): сторона квадрата

    Возвращаемое значение:
        (int): площадь квадрата

    Пример вызова:
        >>> area(4)
        16
    '''
    return a * a

